# KLayout batch render of a GDS (run: klayout -zz -r render.py -rd gds=... -rd lyp=... -rd out=... [-rd width=1600])
import pya
lv = pya.LayoutView()
lv.load_layout(gds, True)
lv.load_layer_props(lyp)
lv.max_hier()
lv.set_config("background-color", "#ffffff")
lv.set_config("grid-visible", "false")
lv.set_config("text-visible", "true")
bb = lv.active_cellview().cell.dbbox()
W = int(globals().get("width", 1600))
H = max(200, int(W * bb.height() / bb.width() * 1.04))
lv.zoom_box(bb.enlarged(bb.width() * 0.02, bb.height() * 0.02))
lv.save_image(out, W, H)
print("saved", out, W, H)
